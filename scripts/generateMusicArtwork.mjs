// Compile the browser lookup from the same manifest used by social previews.
import {readFileSync,writeFileSync} from 'node:fs';
const base=new URL('../web/public/music/',import.meta.url);
const manifest=JSON.parse(readFileSync(new URL('covers/artwork-map.json',base),'utf8'));
const sources=JSON.parse(readFileSync(new URL('covers/photo-sources.json',base),'utf8'));
for(const name of [manifest.default,...Object.values(manifest.byObjectKey),...Object.values(manifest.byTrackId)]){
 if(!sources[name])throw Error('Missing music artwork source: '+name);
}
const content=`// Generated by scripts/generateMusicArtwork.mjs; edit covers/artwork-map.json.\nconst artwork=${JSON.stringify(manifest,null,2)};\nconst paths=${JSON.stringify(Object.fromEntries(Object.entries(sources).map(([k,v])=>[k,v.path])),null,2)};\nexport function coverForTrack(track){\n  if(!track || typeof track!=="object")return "";\n  const key=String(track.objectKey||"");\n  if(key && !/^music\\/(a1|a2|b1|b2|c1|c2)\\/day-\\d{2}\\/[^/\\\\]+\\.mp3$/i.test(key))return "";\n  const name=artwork.byObjectKey[key] || artwork.byTrackId[String(track.id||"")] || artwork.default;\n  return paths[name];\n}\n`;
const dest=new URL('cover-art.js',base);
if(process.argv.includes('--check')){
 if(readFileSync(dest,'utf8')!==content)throw Error('Run node scripts/generateMusicArtwork.mjs');
}else writeFileSync(dest,content);
